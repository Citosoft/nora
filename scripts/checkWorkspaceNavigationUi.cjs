const { app } = require('electron');
const assert = require('node:assert/strict');
const { createFixtureHost } = require('./ui/fixtureHost.cjs');
let host;
(async () => {
  host = await createFixtureHost('tests/ui/WorkspaceNavigationHarness.tsx');
  const { click, wait, evaluate, window, pause } = host;
  const state = async () => JSON.parse(await evaluate(`document.querySelector('#navigation-state').textContent`));
  await wait(`!!document.querySelector('textarea')`);
  await click('textarea');
  window.webContents.insertText('Keep this thread draft');
  await pause(100);
  await evaluate(`window.originalComposer=document.querySelector('textarea')`);
  await click('#open-tool');
  await wait(`!!document.querySelector('button[aria-label="Close documents"]')`);
  assert.equal((await state()).route.tool, 'documents');
  assert.equal(await evaluate(`window.originalComposer===document.querySelector('textarea') && window.originalComposer.value==='Keep this thread draft'`), true);
  assert.equal(await evaluate(`(()=>{window.originalComposer.focus();return !!window.originalComposer.closest('[inert]')&&document.activeElement!==window.originalComposer})()`), true);
  await click('button[aria-label="Close documents"]');
  await wait(`!document.querySelector('button[aria-label="Close documents"]')`);
  assert.equal((await state()).route, null);
  assert.equal(await evaluate(`window.originalComposer===document.querySelector('textarea')`), true);
  await click('#open-tool');
  await click('#thread');
  await wait(`!document.querySelector('button[aria-label="Close documents"]')`);
  await click('#open-tool');
  await click('#workspace');
  await wait(`!document.querySelector('button[aria-label="Close documents"]')`);
  await click('#workspace');
  assert.equal((await state()).route?.tool, 'documents', 'Returning to a workspace resumes its last tool');
  await click('#pin');
  await wait(`JSON.parse(localStorage.getItem('nora-sidebar-navigation')).pinnedWorkspaceIds.includes('shell')`);
  assert.deepEqual((await state()).preferences.pinnedWorkspaceIds, ['shell'], 'StrictMode must not duplicate updater side effects');
  await click('#storage-fail');
  await click('#pin');
  await wait(`JSON.parse(document.querySelector('#navigation-state').textContent).error!==null`);
  assert.equal((await state()).preferences.pinnedWorkspaceIds.length, 2, 'Storage failure retains in-memory choices');
  await click('#storage-recover');
  await click('#pin');
  await wait(`JSON.parse(document.querySelector('#navigation-state').textContent).error===null`);
  console.log('PASS: mounted draft identity, inert keyboard focus, close and thread navigation, workspace route invalidation, StrictMode preferences and storage recovery.');
})().then(async () => { await host?.close(); app.exit(0); }).catch(async error => { console.error(error); await host?.close(); app.exit(1); });
