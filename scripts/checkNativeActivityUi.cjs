const { app } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const { join } = require('node:path');
const { createFixtureHost } = require('./ui/fixtureHost.cjs');
let host;
(async () => {
  host = await createFixtureHost('tests/ui/NativeActivityHarness.tsx');
  const { evaluate, wait, click, byText, window, pause } = host;
  const history = 'details[aria-label="Turn tool history"]';
  await wait('document.querySelectorAll("details").length===4');
  const timer = '[aria-label="Turn elapsed time"]';
  const initialTime = await evaluate(`document.querySelector(${JSON.stringify(timer)}).textContent`);
  assert.match(initialTime, /Elapsed 1m \d+s/);
  await wait(`document.querySelector(${JSON.stringify(timer)}).textContent!==${JSON.stringify(initialTime)}`);
  assert.equal(await evaluate(`document.querySelector(${JSON.stringify(history)}).open`), false);
  assert.equal(await evaluate(`document.querySelector(${JSON.stringify(history + ' > summary')}).textContent.includes('Search documentation')`), true);
  assert.equal(await evaluate(`document.querySelector(${JSON.stringify(history + ' > summary')}).textContent.includes('1 failed')`), true);
  await click('#next-tool');
  await wait(`document.querySelector(${JSON.stringify(history + ' > summary')}).textContent.includes('Read project files')`);
  assert.equal(await evaluate(`document.querySelectorAll(${JSON.stringify(history)}).length`), 1);
  await evaluate(`document.querySelector(${JSON.stringify(history + ' > summary')}).focus()`);
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Space' });
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Space' });
  await wait(`document.querySelector(${JSON.stringify(history)}).open`);
  assert.equal(await evaluate('document.querySelector(\'details[aria-label="Fetch page: Failed"]\').open'), false);
  const rowAppearance = await evaluate(`(()=>{const row=document.querySelector('details[aria-label="Run command: Done"]');const style=getComputedStyle(row);const summary=row.querySelector('summary');return {border:style.borderTopWidth,background:style.backgroundColor,height:summary.getBoundingClientRect().height,nowrap:getComputedStyle(summary.querySelector('span.flex-1')).whiteSpace}})()`);
  assert.equal(rowAppearance.border, '0px');
  assert.equal(rowAppearance.background, 'rgba(0, 0, 0, 0)');
  assert.ok(rowAppearance.height <= 32, 'Tool rows should fit a single compact line');
  assert.equal(rowAppearance.nowrap, 'nowrap');
  await click('details[aria-label="Fetch page: Failed"] summary');
  await click('details[aria-label="Run command: Done"] summary');
  assert.equal(await evaluate('document.querySelector(\'details[aria-label="Run command: Done"]\').open'), true);
  assert.equal(await evaluate('document.body.textContent.includes("Exit code 0")'), true);
  await click('details[aria-label="Search documentation: Done"] summary');
  await evaluate('document.querySelector(\'details[aria-label="Search documentation: Done"] summary\').focus()');
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Space' });
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Space' });
  await wait('!document.querySelector(\'details[aria-label="Search documentation: Done"]\').open');
  await click('details[aria-label="Search documentation: Done"] summary');
  await wait('document.querySelector(\'details[aria-label="Search documentation: Done"]\').open');
  await click('details[aria-label="Search documentation: Done"] summary');
  await click('details[aria-label="Run command: Done"] summary');
  await click('details[aria-label="Fetch page: Failed"] summary');
  await click('#finish-tools');
  await wait(`document.querySelector(${JSON.stringify(history + ' > summary')}).textContent.includes('4 tool calls')`);
  const finalTime = await evaluate('document.querySelector(\'[aria-label="Turn duration"]\').textContent');
  await pause(1100);
  assert.equal(await evaluate('document.querySelector(\'[aria-label="Turn duration"]\').textContent'), finalTime);
  assert.equal(await evaluate(`document.querySelector(${JSON.stringify(history)}).open`), true, 'Live updates preserve expansion');
  await click(history + ' > summary');
  if (process.env.NORA_UI_EVIDENCE_DIR) {
    await fs.mkdir(process.env.NORA_UI_EVIDENCE_DIR, { recursive: true });
    for (const theme of ['light', 'dark']) {
      await evaluate(`document.documentElement.classList.toggle('dark','${theme}'==='dark');document.documentElement.dataset.theme='${theme}'`);
      await pause(100);
      await fs.writeFile(join(process.env.NORA_UI_EVIDENCE_DIR, `activity-${theme}.png`), (await window.webContents.capturePage()).toPNG());
    }
  }
  await click('#fail');
  await byText('Allow onceAllow only this action.');
  await wait('!!document.querySelector("[role=alert]")');
  assert.equal(await evaluate('document.getElementById("responses").textContent'), '[]');
  await click('#fail');
  await byText('Allow onceAllow only this action.');
  assert.equal(await evaluate('[...document.querySelectorAll(\'section[aria-label="Agent request"] button\')].every(button=>button.disabled)'), true);
  await wait('document.body.textContent.includes("Delivering response")');
  assert.deepEqual(JSON.parse(await evaluate('document.getElementById("responses").textContent')), [{ kind: 'approval', optionId: 'accept' }]);
  await click('#network');
  assert.equal(await evaluate('document.body.textContent.includes("https://api.example.com")'), true);
  await click('#files');
  assert.equal(await evaluate('document.querySelector(\'ul[aria-label="Affected files"]\').children.length'), 2);
  await click('#expire');
  assert.equal(await evaluate('[...document.querySelectorAll(\'section[aria-label="Agent request"] button\')].every(button=>button.disabled)'), true);
  console.log('PASS: tool details, keyboard expansion, approval context/scopes, pending lock, delivery, retry, network/files and expired state.');
})().then(async () => { await host?.close(); app.exit(0); }).catch(async error => {
  console.error(error); if (host) console.error(await host.evaluate('document.body.innerText').catch(()=>'Renderer unavailable'));
  await host?.close(); app.exit(1);
});
